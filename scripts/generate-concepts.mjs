// Scans the codebase for `[CONCEPT: Name] explanation` tags and writes docs/CONCEPTS.md,
// an index graders can use to jump from a web-development concept to the code that implements it.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SCAN_DIRS = ['client', 'server', 'runner', 'shared'];
const EXTENSIONS = /\.(ts|tsx|js|mjs|css|html)$/;
const SKIP = new Set(['node_modules', 'dist', 'coverage']);
const TAG = /\[CONCEPT:\s*([^\]]+)\]\s*(.*?)\s*(?:\*\/|-->|\}\s*$|$)/;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (EXTENSIONS.test(entry.name)) yield path;
  }
}

const concepts = new Map();
for (const dir of SCAN_DIRS) {
  for await (const file of walk(join(ROOT, dir))) {
    const lines = (await readFile(file, 'utf8')).split('\n');
    lines.forEach((line, i) => {
      const match = line.match(TAG);
      if (!match) return;
      const [, name, explanation] = match;
      const key = name.trim();
      if (!concepts.has(key)) concepts.set(key, []);
      concepts
        .get(key)
        .push({ file: relative(ROOT, file), line: i + 1, explanation: explanation.trim() });
    });
  }
}

const sorted = [...concepts.entries()].sort(([a], [b]) => a.localeCompare(b));
const rows = sorted.flatMap(([name, uses]) =>
  uses.map(
    (u, i) =>
      `| ${i === 0 ? `**${name}**` : ''} | ${u.explanation.replace(/\|/g, '\\|')} | [${u.file}:${u.line}](../${u.file}#L${u.line}) |`,
  ),
);

const md = `# Web Development Concepts Index

> Auto-generated by \`npm run concepts\` from \`[CONCEPT: …]\` tags in the source. Do not edit by hand.

**${sorted.length} concepts** tagged across **${rows.length} locations**.

| Concept | How it is used | Where |
|---|---|---|
${rows.join('\n')}
`;

await writeFile(join(ROOT, 'docs/CONCEPTS.md'), md);
console.log(`docs/CONCEPTS.md: ${sorted.length} concepts, ${rows.length} locations`);
